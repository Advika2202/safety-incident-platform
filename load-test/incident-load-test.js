import http from "k6/http";
import { check, sleep } from "k6";

const BASE_URL = __ENV.BASE_URL || "http://localhost:4000";

export const options = {
  stages: [
    { duration: "20s", target: 20 }, // ramp up
    { duration: "40s", target: 50 }, // hold at 50 concurrent users
    { duration: "20s", target: 0 },  // ramp down
  ],
  thresholds: {
    http_req_duration: ["p(95)<500"], // 95% of requests under 500ms
    http_req_failed: ["rate<0.01"],   // less than 1% errors
  },
};

// Runs once before the load starts: create one worker + one manager
// account and share their tokens across every virtual user.
export function setup() {
  const suffix = Date.now();
  const headers = { headers: { "Content-Type": "application/json" } };

  const workerRes = http.post(
    `${BASE_URL}/api/auth/signup`,
    JSON.stringify({
      email: `loadtest-worker-${suffix}@site.com`,
      password: "password123",
      name: "Load Test Worker",
      role: "WORKER",
    }),
    headers
  );

  const managerRes = http.post(
    `${BASE_URL}/api/auth/signup`,
    JSON.stringify({
      email: `loadtest-manager-${suffix}@site.com`,
      password: "password123",
      name: "Load Test Manager",
      role: "MANAGER",
    }),
    headers
  );

  return {
    workerToken: workerRes.json("token"),
    managerToken: managerRes.json("token"),
  };
}

// Simulates the two real hot paths: a worker filing a report, a manager
// pulling the live incident feed.
export default function (data) {
  const writeRes = http.post(
    `${BASE_URL}/api/incidents`,
    JSON.stringify({
      title: `Load test incident ${__VU}-${__ITER}`,
      description: "Synthetic incident generated by k6 load test.",
      category: "HAZARD",
      severity: "MEDIUM",
      location: "Load Test Site",
    }),
    {
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${data.workerToken}`,
      },
    }
  );
  check(writeRes, { "create incident -> 201": (r) => r.status === 201 });

  const readRes = http.get(`${BASE_URL}/api/incidents`, {
    headers: { Authorization: `Bearer ${data.managerToken}` },
  });
  check(readRes, { "list incidents -> 200": (r) => r.status === 200 });

  sleep(1);
}
